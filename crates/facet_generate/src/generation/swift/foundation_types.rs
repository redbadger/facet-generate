//! The types that `import Foundation` brings into scope.

/// The public top-level types that a module importing `Foundation` finds
/// (structs, enums, classes, protocols and typealiases, whether declared in
/// Swift or imported from C or Objective-C), each with the module that
/// declares it, less those that start with `_`, those no namespace becomes
/// (`URL`, `NSObject`) and those in scope without `Foundation`. Sorted by
/// name.
///
/// Swift looks a qualifier up as a type before it looks for a module, so in a
/// module that imports `Foundation` itself, a module named like one of these
/// cannot be qualified: `Data.Foo` looks for `Foo` in `Foundation.Data`. The
/// import is not transitive: a module that imports only `Serde`, or another
/// module, which imports `Foundation` does not find these.
//
// Generated with Apple Swift 6.4 (swiftlang-6.4.0.34.1), macOS 27.0 SDK. The
// candidates are the names of the symbols of kind `swift.{struct,enum,class,
// protocol,actor,typealias}` with a single path component in the graphs that
// `swift-symbolgraph-extract -minimum-access-level public -target
// arm64-apple-macosx27.0` writes for `Foundation` and for every module that a
// file holding only `import Foundation` loads (the `.pcm`s in a fresh
// `-module-cache-path`, and its `-emit-loaded-module-trace`), keeping each
// that does not start with `_` and for which
// `name.to_snake_case().to_upper_camel_case() == name` (heck 0.5). Of those,
// each is kept for which `swiftc -typecheck` of `import Foundation` and
// `public typealias P = Name.Missing` fails with "'Missing' is not a member
// type of ... 'Module.Name'" (the module is the one it names), and for which
// the same without the import fails with "cannot find type". Sorted

#[cfg(test)]
mod tests {
    use heck::{ToSnakeCase as _, ToUpperCamelCase as _};

    use super::FOUNDATION_TYPES;

    #[test]
    fn is_sorted_for_binary_search() {
        assert!(
            FOUNDATION_TYPES.windows(2).all(|w| w[0].0 < w[1].0),
            "FOUNDATION_TYPES must be sorted by name"
        );
    }

    #[test]
    fn holds_only_names_a_namespace_becomes() {
        for (name, _) in FOUNDATION_TYPES {
            assert!(!name.starts_with('_'), "{name}");
            assert_eq!(name.to_snake_case().to_upper_camel_case(), *name);
        }
    }
}
